// Generate crates/dsp/src/kemar_hrir.rs from the MIT Media Lab KEMAR
// diffuse-field equalized HRTF set (diffuse.zip).
//
// Source data: Bill Gardner and Keith Martin, "HRTF Measurements of a KEMAR
// Dummy-Head Microphone", MIT Media Lab Perceptual Computing Technical Report
// #280, May 1994. https://sound.media.mit.edu/resources/KEMAR.html
// "This data is Copyright 1994 by the MIT Media Laboratory. It is provided free
// with no restrictions on use, provided the authors are cited when the data is
// used in any research or commercial application."
//
// Usage (after extracting diffuse.zip):
//   node tools/hrtf/generate-kemar-table.mjs <diffuse-dir> crates/dsp/src/kemar_hrir.rs
//
// Each elev0/H0eAAAa.wav holds a 44.1 kHz 16-bit stereo (left ear, right ear)
// 128-point pair for a source AAA degrees to the right. This script resamples
// the selected azimuths to 48 kHz with a Blackman-windowed sinc and scales the
// whole table so the frontal (0 degree) left-ear response has unit energy.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [sourceDir, outputPath] = process.argv.slice(2);
if (!sourceDir || !outputPath) {
  console.error("usage: generate-kemar-table.mjs <diffuse-dir> <output.rs>");
  process.exit(2);
}

const AZIMUTHS = [0, 30, 90, 150];
const SOURCE_RATE = 44_100;
const TARGET_RATE = 48_000;
const ZERO_CROSSINGS = 16;

function readPair(azimuth) {
  const name = `H0e${String(azimuth).padStart(3, "0")}a.wav`;
  const bytes = readFileSync(join(sourceDir, "elev0", name));
  if (bytes.toString("ascii", 0, 4) !== "RIFF" || bytes.toString("ascii", 8, 12) !== "WAVE") {
    throw new Error(`${name}: not a RIFF/WAVE file`);
  }
  let offset = 12;
  let format = null;
  while (offset + 8 <= bytes.length) {
    const id = bytes.toString("ascii", offset, offset + 4);
    const size = bytes.readUInt32LE(offset + 4);
    const body = offset + 8;
    if (id === "fmt ") {
      format = {
        tag: bytes.readUInt16LE(body),
        channels: bytes.readUInt16LE(body + 2),
        rate: bytes.readUInt32LE(body + 4),
        bits: bytes.readUInt16LE(body + 14),
      };
    } else if (id === "data") {
      if (!format || format.tag !== 1 || format.channels !== 2 || format.rate !== SOURCE_RATE || format.bits !== 16) {
        throw new Error(`${name}: expected 44.1 kHz 16-bit stereo PCM`);
      }
      const frames = size / 4;
      const left = new Float64Array(frames);
      const right = new Float64Array(frames);
      for (let frame = 0; frame < frames; frame += 1) {
        left[frame] = bytes.readInt16LE(body + frame * 4) / 32768;
        right[frame] = bytes.readInt16LE(body + frame * 4 + 2) / 32768;
      }
      return [left, right];
    }
    offset = body + size + (size % 2);
  }
  throw new Error(`${name}: missing data chunk`);
}

function resample(input) {
  const ratio = TARGET_RATE / SOURCE_RATE;
  const length = Math.ceil(input.length * ratio);
  const output = new Float64Array(length);
  for (let n = 0; n < length; n += 1) {
    const position = n / ratio;
    let sum = 0;
    const first = Math.ceil(position - ZERO_CROSSINGS);
    const last = Math.floor(position + ZERO_CROSSINGS);
    for (let k = Math.max(0, first); k <= Math.min(input.length - 1, last); k += 1) {
      const x = position - k;
      const sinc = x === 0 ? 1 : Math.sin(Math.PI * x) / (Math.PI * x);
      const w = 0.42 + 0.5 * Math.cos((Math.PI * x) / ZERO_CROSSINGS) + 0.08 * Math.cos((2 * Math.PI * x) / ZERO_CROSSINGS);
      sum += input[k] * sinc * w;
    }
    output[n] = sum;
  }
  return output;
}

const pairs = AZIMUTHS.map((azimuth) => readPair(azimuth).map(resample));
const taps = pairs[0][0].length;
const reference = Math.sqrt(pairs[0][0].reduce((sum, value) => sum + value * value, 0));
const scale = 1 / reference;
const format = (values) => values.map((value) => (value * scale).toExponential(8)).join(", ");

const lines = [
  "// @generated by tools/hrtf/generate-kemar-table.mjs; do not edit by hand.",
  "//",
  "// Head-related impulse responses derived from the MIT Media Lab KEMAR",
  "// diffuse-field equalized set: Bill Gardner and Keith Martin, \"HRTF",
  "// Measurements of a KEMAR Dummy-Head Microphone\", MIT Media Lab Perceptual",
  "// Computing Technical Report #280, 1994.",
  "// https://sound.media.mit.edu/resources/KEMAR.html",
  "// Copyright 1994 by the MIT Media Laboratory; provided free with no",
  "// restrictions on use, provided the authors are cited.",
  "//",
  "// Resampled from 44.1 kHz to 48 kHz; scaled so the frontal left-ear",
  "// response has unit energy. Indexed [azimuth][ear], ear 0 = left, for a",
  "// source on the listener's right at the listed azimuth (0 = front).",
  "",
  `pub(crate) const KEMAR_AZIMUTHS_DEG: [u16; ${AZIMUTHS.length}] = [${AZIMUTHS.join(", ")}];`,
  `pub(crate) const KEMAR_TAPS: usize = ${taps};`,
  "",
  "#[rustfmt::skip]",
  `pub(crate) static KEMAR_HRIR_48K: [[[f32; KEMAR_TAPS]; 2]; ${AZIMUTHS.length}] = [`,
];
for (const [index, [left, right]] of pairs.entries()) {
  lines.push(`    // ${AZIMUTHS[index]} degrees`);
  lines.push(`    [[${format(left)}],`);
  lines.push(`     [${format(right)}]],`);
}
lines.push("];", "");
writeFileSync(outputPath, lines.join("\n"));
console.log(`wrote ${outputPath}: ${AZIMUTHS.length} azimuths x 2 ears x ${taps} taps`);
