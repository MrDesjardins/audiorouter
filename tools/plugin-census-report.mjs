// Turns plugin census reports into docs/operations/plugin-census.md.
//
// The census itself is the opt-in test `plugin_census` in
// crates/control/src/plugin_census_tests.rs; it writes a JSON report
// (AUDIOROUTER_CENSUS_REPORT). This script only formats such reports. It never
// loads a plugin.
//
//   node tools/plugin-census-report.mjs <version> <date> <report.json> [more.json ...]
//
// Only file names are published: a report holds full paths, which include the
// tester's user folder.
import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const [version, date, ...reports] = process.argv.slice(2);
if (!version || !/^\d{4}-\d{2}-\d{2}$/.test(date ?? "") || reports.length === 0) {
  console.error("usage: node tools/plugin-census-report.mjs <version> <YYYY-MM-DD> <report.json> [...]");
  process.exit(2);
}

const fileName = (path) => basename(String(path).replaceAll("\\", "/"));
const short = (text) => {
  const reason = String(text);
  const instrument = /is an instrument/.test(reason);
  if (instrument) return "refused: it is an instrument";
  const worker = /native worker diagnostic: ([^"\\]+)/.exec(reason)?.[1];
  return (worker ?? reason).replace(/\s+/g, " ").slice(0, 120);
};

// One width (mono or stereo) of an effect: the problems found, or none.
function widthProblems(width) {
  if (!width) return ["not run"];
  if (typeof width.failed === "string") return [`failed: ${short(width.failed)}`];
  const problems = [];
  if (typeof width.audioError === "string") problems.push(`audio error: ${short(width.audioError)}`);
  if (width.nonFinite === true) problems.push("non-finite output");
  if (width.silent === true) problems.push("silent");
  if (width.stateSaved === false) problems.push("state not saved");
  if (width.restoreSame != null || width.restoreFresh != null) problems.push("state not restored");
  if (width.cleanExit === false) problems.push("did not close cleanly");
  return problems;
}

const rows = new Map();
for (const report of reports) {
  for (const plugin of JSON.parse(readFileSync(report, "utf8")).plugins ?? []) {
    if (plugin.skipped === "not a supported effect" || plugin.refused) continue;
    const name = fileName(plugin.path);
    const key = `${name}\0${plugin.format}\0${plugin.architecture}`;
    if (plugin.skipped) {
      rows.set(key, { name, plugin, kind: "skipped", result: "not run (left out of this run)", ok: null });
      continue;
    }
    if (plugin.instrument) {
      const instrument = plugin.instrument;
      const failed = typeof instrument.failed === "string";
      const ok = !failed && instrument.sounds === true && instrument.nonFinite !== true;
      rows.set(key, {
        name,
        plugin,
        kind: "instrument",
        ok,
        result: failed
          ? `failed: ${short(instrument.failed)}`
          : ok
            ? "plays a note"
            : instrument.nonFinite === true
              ? "non-finite output"
              : "loads, silent with a note held",
      });
      continue;
    }
    const [mono, stereo] = [widthProblems(plugin.widths?.[0]), widthProblems(plugin.widths?.[1])];
    const ok = mono.length === 0 && stereo.length === 0;
    const describe = (label, problems) => (problems.length ? `${label}: ${problems.join(", ")}` : null);
    const passThrough = (plugin.widths ?? []).some((width) => width.changesSignal === false);
    rows.set(key, {
      name,
      plugin,
      kind: "effect",
      ok,
      result: ok
        ? `ok${passThrough ? " (default settings leave the test tone unchanged)" : ""}`
        : [describe("mono", mono), describe("stereo", stereo)].filter(Boolean).join("; "),
    });
  }
}

const sorted = [...rows.values()].sort(
  (a, b) =>
    a.name.localeCompare(b.name, "en", { sensitivity: "base" }) ||
    String(a.plugin.format).localeCompare(String(b.plugin.format)) ||
    String(a.plugin.architecture).localeCompare(String(b.plugin.architecture)),
);
const count = (kind, ok) => sorted.filter((row) => row.kind === kind && row.ok === ok).length;
const bits = (architecture) => (architecture === "X86" ? "32" : architecture === "X64" ? "64" : "?");
const table = (kind) =>
  [
    "| Plugin file | Format | Bits | Result |",
    "| --- | --- | --- | --- |",
    ...sorted
      .filter((row) => row.kind === kind)
      .map(
        (row) =>
          `| ${row.name} | ${String(row.plugin.format).toUpperCase()} | ${bits(row.plugin.architecture)} | ${row.result.replaceAll("|", "/")} |`,
      ),
  ].join("\n");

const effects = sorted.filter((row) => row.kind === "effect").length;
const instruments = sorted.filter((row) => row.kind === "instrument").length;
const skipped = sorted.filter((row) => row.kind === "skipped").length;
const text = `# Plugin census

Generated by \`tools/plugin-census-report.mjs\` from the \`plugin_census\` test
reports. Do not edit by hand; run the census and the script again.

- AudioRouter version: ${version}
- Date: ${date}
- Effects: ${count("effect", true)} of ${effects} passed every step
- Instruments: ${count("instrument", true)} of ${instruments} played a note
${skipped ? `- Left out of this run: ${skipped}\n` : ""}
## What the census does

Each effect is started in its real isolated worker (64-bit or 32-bit, VST2 or
VST3), fed a 220 Hz tone for 100 blocks at mono and at stereo, asked to save its
state, then asked to restore it in the same worker and in a fresh one. "ok"
means every step worked and the output was finite and not silent. Each
instrument is started in stereo, checked for silence, then given one held note.

It opens no audio device and no plugin window, so it says nothing about
editors, about how a plugin sounds, or about a plugin on a live route. A plugin
that needs its vendor's licence app can load and still produce silence.

## Effects

${table("effect")}

## Instruments

${table("instrument")}
${skipped ? `\n## Left out\n\n${table("skipped")}\n` : ""}`;

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "docs/operations/plugin-census.md");
writeFileSync(output, text.endsWith("\n") ? text : `${text}\n`, "utf8");
console.log(
  `Wrote ${output}: ${effects} effects (${count("effect", true)} ok), ${instruments} instruments (${count("instrument", true)} play), ${skipped} left out.`,
);
