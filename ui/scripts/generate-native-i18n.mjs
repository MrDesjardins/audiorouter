/**
 * Generate the native shell's language lookup from the same UI catalogs.
 * Only `messages.native.*` is emitted: the shell never needs the rest of the
 * interface text. The output is committed and checked by `i18n:check`.
 */
import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { LOCALE_DIR, flattenMessages, localeFiles } from "./i18n-catalog.mjs";

const OUTPUT = path.resolve("..", "src-tauri", "src", "ui_language.rs");

const languages = localeFiles().map((file) => {
  const tag = file.replace(/\.json$/i, "");
  const catalog = JSON.parse(readFileSync(path.join(LOCALE_DIR, file), "utf8"));
  const problems = [];
  const flat = flattenMessages(catalog.messages, [], problems);
  if (problems.length > 0) {
    for (const problem of problems) console.error(`${file}: ${problem}`);
    process.exit(1);
  }
  return { tag, messages: flat, meta: catalog.meta };
});

const english = languages.find((language) => language.tag === "en");
if (!english) {
  console.error("en.json is required as the native reference catalog");
  process.exit(1);
}

function nativeKeys(messages) {
  return Object.keys(messages)
    .filter((key) => key.startsWith("native."))
    .sort();
}

function rustString(value) {
  return JSON.stringify(value);
}

function textFunction(language) {
  const keys = nativeKeys(language.messages);
  const arms = keys.map((key) => `        ${rustString(key)} => ${rustString(language.messages[key])},`).join("\n");
  return `fn text_${language.tag.replace(/-/g, "_")}(key: &str) -> &'static str {
    match key {
${arms}
        _ => "",
    }
}`;
}

const supported = languages.map((language) => rustString(language.tag)).join(", ");
const dispatch = languages
  .map((language) => `        ${rustString(language.tag)} => text_${language.tag.replace(/-/g, "_")}(key),`)
  .join("\n");

const source = `// @generated by ui/scripts/generate-native-i18n.mjs. Do not edit by hand.
// Run \`npm --prefix ui run i18n:generate\` after changing a language catalog.
//! Native shell text drawn from the interface catalogs.

pub const SUPPORTED: &[&str] = &[${supported}];

/// One canonical supported tag, or \`None\` for an unsupported or malformed tag.
pub fn canonical(candidate: &str) -> Option<&'static str> {
    let normalized = candidate.trim().replace('_', "-").to_ascii_lowercase();
    SUPPORTED
        .iter()
        .copied()
        .find(|tag| tag.to_ascii_lowercase() == normalized)
}

/// Exact tag first, then progressively broader parents (fr-CA -> fr,
/// zh-Hant-TW -> zh-Hant -> zh).
fn match_with_parents(candidate: &str) -> Option<&'static str> {
    let mut parts: Vec<String> = candidate
        .trim()
        .replace('_', "-")
        .split('-')
        .filter(|part| !part.is_empty())
        .map(str::to_ascii_lowercase)
        .collect();
    while !parts.is_empty() {
        let joined = parts.join("-");
        if let Some(tag) = SUPPORTED
            .iter()
            .copied()
            .find(|tag| tag.to_ascii_lowercase() == joined)
        {
            return Some(tag);
        }
        parts.pop();
    }
    None
}

/// A saved choice, then the ordered system languages, then English.
pub fn resolve(preference: Option<&str>, system: &[String]) -> &'static str {
    if let Some(tag) = preference.and_then(match_with_parents) {
        return tag;
    }
    for candidate in system {
        if let Some(tag) = match_with_parents(candidate) {
            return tag;
        }
    }
    SUPPORTED.first().copied().unwrap_or("en")
}

pub fn text(language: &str, key: &str) -> &'static str {
    match language {
${dispatch}
        _ => text_en(key),
    }
}

/// Replace \`{{name}}\` placeholders. Values never reorder the sentence: the
/// catalog controls word order.
pub fn format(language: &str, key: &str, values: &[(&str, &str)]) -> String {
    let mut text = text(language, key).to_owned();
    for (name, value) in values {
        text = text.replace(&format!("{{{{{name}}}}}"), value);
    }
    text
}

${languages.map(textFunction).join("\n\n")}
`;

/** The repository's rustfmt must own .rs formatting, so format before comparing. */
function rustfmt(text) {
  const temporary = path.join(os.tmpdir(), `audiorouter-ui-language-${process.pid}.rs`);
  writeFileSync(temporary, text, "utf8");
  const result = spawnSync("rustfmt", ["--edition", "2021", temporary], { encoding: "utf8" });
  const formatted = result.status === 0 ? readFileSync(temporary, "utf8") : text;
  if (result.status !== 0) console.error(result.stderr || "rustfmt failed");
  try {
    unlinkSync(temporary);
  } catch {
    /* best effort */
  }
  return formatted;
}

const formatted = rustfmt(source);
if (process.argv.includes("--check")) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : null;
  if (!current || current.replace(/\r\n/g, "\n") !== formatted.replace(/\r\n/g, "\n")) {
    console.error("src-tauri/src/ui_language.rs is stale; run i18n:generate");
    process.exitCode = 1;
  }
} else {
  writeFileSync(OUTPUT, formatted, "utf8");
  console.log(`Generated native text for ${languages.length} language(s): ${OUTPUT}`);
}
